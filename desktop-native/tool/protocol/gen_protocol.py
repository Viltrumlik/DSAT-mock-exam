#!/usr/bin/env python3
"""Generate the island message protocol bindings from island/protocol/schema.json.

    python3 -I desktop-native/tool/protocol/gen_protocol.py

Writes (never edit these by hand):
  * desktop-native/island/src/protocol.ts        — TS types, type guards, validator
  * desktop-native/app/lib/island/protocol.dart  — Dart classes, parser, validator

Both embed the schema verbatim and validate with the same small interpreter, so a message
one side accepts the other side accepts too. The tests in both languages check the same
examples (island/protocol/examples/**) and that the embedded schema equals schema.json.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # desktop-native/
SCHEMA_PATH = ROOT / "island" / "protocol" / "schema.json"
TS_OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "island" / "src" / "protocol.ts"
DART_OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "app" / "lib" / "island" / "protocol.dart"

PRIMS = {"string", "int", "number", "bool", "any"}


def load():
    text = SCHEMA_PATH.read_text(encoding="utf-8")
    return text, json.loads(text)


def pascal(t: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", t)
    out = ""
    for p in parts:
        if not p:
            continue
        out += p[0].upper() + p[1:]
    return out


def msg_class(t: str) -> str:
    return pascal(t) + "Message"


def split_field(name: str):
    return (name[:-1], True) if name.endswith("?") else (name, False)


def type_class(name: str) -> str:
    return "Island" + name


# ------------------------------------------------------------------------------------------------
# TypeScript
# ------------------------------------------------------------------------------------------------

def ts_type(spec, types) -> str:
    if isinstance(spec, str):
        return {"string": "string", "int": "number", "number": "number", "bool": "boolean", "any": "unknown"}[spec]
    if "nullable" in spec:
        return f"{ts_type(spec['nullable'], types)} | null"
    if "enum" in spec:
        return " | ".join(json.dumps(v) for v in spec["enum"])
    if spec.get("type") == "string":
        return "string"
    if "array" in spec:
        inner = ts_type(spec["array"], types)
        return f"Array<{inner}>"
    if "map" in spec:
        return f"Record<string, {ts_type(spec['map'], types)}>"
    if "ref" in spec:
        return type_class(spec["ref"])
    raise ValueError(f"unsupported spec {spec}")


def ts_fields(fields, types, indent="  ") -> list[str]:
    lines = []
    for raw, spec in fields.items():
        name, opt = split_field(raw)
        key = name if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) else json.dumps(name)
        lines.append(f"{indent}readonly {key}{'?' if opt else ''}: {ts_type(spec, types)};")
    return lines


def gen_ts(schema_text: str, schema) -> str:
    types = schema["types"]
    msgs = schema["messages"]
    out = [
        "// GENERATED by desktop-native/tool/protocol/gen_protocol.py from island/protocol/schema.json.",
        "// Do not edit. Native <-> web island protocol v1 (architecture.md §2.7).",
        "// Erasable TypeScript only (runs under `node --test` type stripping and Vite alike).",
        "",
        "export const PROTOCOL_VERSION = 1 as const;",
        "",
        "export type Direction = \"to_web\" | \"to_native\";",
        "export type IslandKind = \"content\" | \"desmos\";",
        "",
    ]
    for name, spec in types.items():
        if "object" not in spec:
            raise ValueError("named types must be objects")
        out.append(f"export interface {type_class(name)} {{")
        out += ts_fields(spec["object"], types)
        if spec.get("additional"):
            out.append("  readonly [extra: string]: unknown;")
        out.append("}")
        out.append("")
    for t, m in msgs.items():
        doc = m.get("doc")
        out.append(f"/** `{t}` — {m['direction']}, islands: {', '.join(m['islands'])}.{(' ' + doc) if doc else ''} */")
        out.append(f"export interface {msg_class(t)} {{")
        out.append("  readonly v: 1;")
        out.append(f"  readonly t: {json.dumps(t)};")
        out += ts_fields(m["fields"], types)
        out.append("}")
        out.append("")

    def union(name, pred):
        members = [msg_class(t) for t, m in msgs.items() if pred(m)]
        out.append(f"export type {name} =")
        for i, c in enumerate(members):
            out.append(f"  | {c}{';' if i == len(members) - 1 else ''}")
        out.append("")

    union("IslandMessage", lambda m: True)
    union("ToWebMessage", lambda m: m["direction"] == "to_web")
    union("ToNativeMessage", lambda m: m["direction"] == "to_native")
    union("NativeToContent", lambda m: m["direction"] == "to_web" and "content" in m["islands"])
    union("ContentToNative", lambda m: m["direction"] == "to_native" and "content" in m["islands"])
    union("NativeToDesmos", lambda m: m["direction"] == "to_web" and "desmos" in m["islands"])
    union("DesmosToNative", lambda m: m["direction"] == "to_native" and "desmos" in m["islands"])
    out.append("export type MessageType = IslandMessage[\"t\"];")
    out.append("")
    out.append("/** The schema, embedded verbatim (a test checks it equals schema.json). */")
    out.append(f"export const PROTOCOL_SCHEMA_JSON: string = {json.dumps(schema_text)};")
    out.append("")
    out.append(TS_RUNTIME)
    for t in msgs:
        out.append(f"export function is{msg_class(t)}(value: unknown): value is {msg_class(t)} {{")
        out.append(f"  return validateMessage(value) === null && (value as {{ t: unknown }}).t === {json.dumps(t)};")
        out.append("}")
        out.append("")
    return "\n".join(out)


TS_RUNTIME = r'''
type Spec = string | { readonly [k: string]: unknown };
interface MessageSpec {
  readonly direction: Direction;
  readonly islands: readonly IslandKind[];
  readonly fields: Readonly<Record<string, Spec>>;
}
interface Schema {
  readonly protocol: number;
  readonly types: Readonly<Record<string, Spec>>;
  readonly messages: Readonly<Record<string, MessageSpec>>;
}

export const PROTOCOL_SCHEMA: Schema = JSON.parse(PROTOCOL_SCHEMA_JSON) as Schema;

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function check(v: unknown, spec: Spec, path: string): string | null {
  if (typeof spec === "string") {
    switch (spec) {
      case "string":
        return typeof v === "string" ? null : `${path}: expected string`;
      case "int":
        return typeof v === "number" && Number.isInteger(v) ? null : `${path}: expected integer`;
      case "number":
        return typeof v === "number" && Number.isFinite(v) ? null : `${path}: expected number`;
      case "bool":
        return typeof v === "boolean" ? null : `${path}: expected boolean`;
      case "any":
        return null;
      default:
        return `${path}: unknown type ${spec}`;
    }
  }
  if ("nullable" in spec) return v === null ? null : check(v, spec.nullable as Spec, path);
  if ("enum" in spec) {
    return (spec.enum as unknown[]).includes(v) ? null : `${path}: expected one of ${JSON.stringify(spec.enum)}`;
  }
  if (spec.type === "string") {
    if (typeof v !== "string") return `${path}: expected string`;
    if (typeof spec.maxLength === "number" && v.length > spec.maxLength) return `${path}: longer than ${spec.maxLength}`;
    if (typeof spec.pattern === "string" && !new RegExp(spec.pattern).test(v)) return `${path}: does not match ${spec.pattern}`;
    return null;
  }
  if ("array" in spec) {
    if (!Array.isArray(v)) return `${path}: expected array`;
    if (typeof spec.maxItems === "number" && v.length > spec.maxItems) return `${path}: more than ${spec.maxItems} items`;
    for (let i = 0; i < v.length; i++) {
      const e = check(v[i], spec.array as Spec, `${path}[${i}]`);
      if (e) return e;
    }
    return null;
  }
  if ("map" in spec) {
    if (!isRecord(v)) return `${path}: expected object`;
    for (const [k, x] of Object.entries(v)) {
      const e = check(x, spec.map as Spec, `${path}.${k}`);
      if (e) return e;
    }
    return null;
  }
  if ("ref" in spec) {
    const named = PROTOCOL_SCHEMA.types[spec.ref as string];
    return named ? check(v, named, path) : `${path}: unknown type ${String(spec.ref)}`;
  }
  if ("object" in spec) {
    return checkObject(v, spec.object as Record<string, Spec>, spec.additional === true, path, []);
  }
  return `${path}: unsupported spec`;
}

function checkObject(
  v: unknown,
  fields: Readonly<Record<string, Spec>>,
  additional: boolean,
  path: string,
  reserved: readonly string[],
): string | null {
  if (!isRecord(v)) return `${path}: expected object`;
  const known = new Set<string>(reserved);
  for (const [raw, spec] of Object.entries(fields)) {
    const optional = raw.endsWith("?");
    const name = optional ? raw.slice(0, -1) : raw;
    known.add(name);
    if (!(name in v) || v[name] === undefined) {
      if (optional) continue;
      return `${path}.${name}: missing`;
    }
    const e = check(v[name], spec, `${path}.${name}`);
    if (e) return e;
  }
  if (!additional) {
    for (const k of Object.keys(v)) if (!known.has(k)) return `${path}.${k}: unexpected field`;
  }
  return null;
}

/**
 * Validate a decoded message. Returns null when valid, else a short reason.
 * Pass `direction`/`island` to also check who may send it.
 */
export function validateMessage(
  value: unknown,
  opts: { readonly direction?: Direction; readonly island?: IslandKind } = {},
): string | null {
  if (!isRecord(value)) return "$: expected object";
  if (value.v !== PROTOCOL_VERSION) return "$.v: expected 1";
  if (typeof value.t !== "string") return "$.t: expected string";
  const spec = PROTOCOL_SCHEMA.messages[value.t];
  if (!spec) return `$.t: unknown message type ${value.t}`;
  if (opts.direction && spec.direction !== opts.direction) return `$.t: ${value.t} is not ${opts.direction}`;
  if (opts.island && !spec.islands.includes(opts.island)) return `$.t: ${value.t} is not for the ${opts.island} island`;
  return checkObject(value, spec.fields, false, "$", ["v", "t"]);
}

export function isToNativeMessage(value: unknown, island?: IslandKind): value is ToNativeMessage {
  return validateMessage(value, { direction: "to_native", island }) === null;
}

export function isToWebMessage(value: unknown, island?: IslandKind): value is ToWebMessage {
  return validateMessage(value, { direction: "to_web", island }) === null;
}
'''


# ------------------------------------------------------------------------------------------------
# Dart
