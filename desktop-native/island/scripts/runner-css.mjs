#!/usr/bin/env node
// Copies the runner rules the question card depends on out of the website's globals.css into
// src/content/runner.generated.css, verbatim, each block labelled with its source lines.
//
//   node scripts/runner-css.mjs           regenerate
//   node scripts/runner-css.mjs --check   exit 1 when the committed file is stale
//
// Blocks are found by their opening line, not by line number, so an unrelated edit to
// globals.css moves the labels but keeps the copy exact. A block that disappears fails loudly.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const GLOBALS = resolve(here, "../../../frontend/src/app/globals.css");
const OUT = resolve(here, "../src/content/runner.generated.css");

/** [label, opening-line predicate, optional "end after the block opening with this line"] */
const BLOCKS = [
  ["@theme (design tokens)", (l) => l.startsWith("@theme {")],
  [":root (light tokens)", (l) => l.startsWith(":root {")],
  ["body", (l) => l.startsWith("body {")],
  ["form controls", (l) => l === "button,", "body {"],
  [".katex / .katex-display", (l) => l.startsWith(".katex {"), null, (l) => l.startsWith(".katex-display {")],
  ["scrollbar", (l) => l.startsWith("::-webkit-scrollbar {"), null, (l) => l.startsWith("::-webkit-scrollbar-thumb:hover")],
  [".ts-runner (the runner's UI face)", (l) => l.startsWith(".ts-runner,")],
  ["reduced motion", (l) => l.startsWith("@media (prefers-reduced-motion: reduce) {"), ".ds-anim-slide-right"],
  ["annotation marks + annotating selection", (l) => l.startsWith("mark.ts-annot {"), null, (l) => l.startsWith(".ts-annotating #ts-passage ::-moz-selection")],
];

export function generate(globals) {
  const lines = globals.split("\n");
  const findFrom = (pred, from = 0) => {
    for (let i = from; i < lines.length; i++) if (pred(lines[i])) return i;
    return -1;
  };
  const out = [
    "/* Runner CSS for the content island — COPIED VERBATIM from the website.",
    " *",
    " * Source: frontend/src/app/globals.css (tracked in parity-manifest.json, so `npm run parity`",
    " * fails when it changes). Only the rules the question card depends on are taken; each block",
    " * names its source lines. Tailwind utilities come from the website's Tailwind version",
    " * (4.2.1) scanning the ported components' class strings (see styles.css).",
    " *",
    " * GENERATED by scripts/runner-css.mjs — do not edit by hand.",
    " */",
    "",
  ];
  for (const [label, pred, afterMarker, lastOpener] of BLOCKS) {
    const after = afterMarker ? findFrom((l) => l.includes(afterMarker)) : 0;
    if (after < 0) throw new Error(`runner-css: marker for "${label}" not found in globals.css`);
    const start = findFrom(pred, after);
    if (start < 0) throw new Error(`runner-css: block "${label}" not found in globals.css`);
    const closeFrom = lastOpener ? findFrom(lastOpener, start) : start;
    if (closeFrom < 0) throw new Error(`runner-css: end of "${label}" not found`);
    const end = findFrom((l) => l === "}", closeFrom);
    if (end < 0) throw new Error(`runner-css: closing brace of "${label}" not found`);
    out.push(`/* ── globals.css:${start + 1}-${end + 1} — ${label} ── */`);
    out.push(...lines.slice(start, end + 1));
    out.push("");
  }
  return out.join("\n");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const fresh = generate(readFileSync(GLOBALS, "utf8"));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      /* missing */
    }
    if (current !== fresh) {
      console.error("runner-css: src/content/runner.generated.css is stale — run `node scripts/runner-css.mjs`");
      process.exit(1);
    }
    console.log("runner-css: up to date");
  } else {
    writeFileSync(OUT, fresh);
    console.log(`runner-css: wrote ${OUT}`);
  }
}
