def read_nodes(icons_dir, name):
    src = open(os.path.join(icons_dir, name + ".js"), encoding="utf-8").read()
    alias = re.search(r"export \{ default \} from '\./([a-z0-9-]+)\.js'", src)
    if alias:
        return read_nodes(icons_dir, alias.group(1))
    body = re.search(r"const __iconNode = (\[.*?\]);\nconst ", src, re.S).group(1)
    nodes = []
    for tag, attrs in re.findall(r'\[\s*"([a-z]+)",\s*\{(.*?)\}\s*\]', body, re.S):
        a = dict(re.findall(r'(\w+): "([^"]*)"', attrs))
        a.pop("key", None)
        nodes.append((tag, a))
    return nodes


def dart_node(tag, a):
    f = lambda k, d="0": float(a.get(k, d))
    if tag == "path":
        return "LucideNode.path(%s)" % json.dumps(a["d"])
    if tag == "circle":
        return "LucideNode.circle(%r, %r, %r)" % (f("cx"), f("cy"), f("r"))
    if tag == "ellipse":
        return "LucideNode.ellipse(%r, %r, %r, %r)" % (f("cx"), f("cy"), f("rx"), f("ry"))
    if tag == "rect":
        rx = f("rx", a.get("ry", "0"))
        ry = f("ry", a.get("rx", "0"))
        return "LucideNode.rect(%r, %r, %r, %r, %r, %r)" % (f("x"), f("y"), f("width"), f("height"), rx, ry)
    if tag == "line":
        return "LucideNode.line(%r, %r, %r, %r)" % (f("x1"), f("y1"), f("x2"), f("y2"))
    if tag in ("polyline", "polygon"):
        pts = [float(p) for p in re.split(r"[\s,]+", a["points"].strip())]
        return "LucideNode.poly(const %r, closed: %s)" % (pts, "true" if tag == "polygon" else "false")
    raise SystemExit("unsupported lucide node: " + tag)


def main():
    root = sys.argv[1]
    version = json.load(open(os.path.join(root, "package.json")))["version"]
    if version != "0.577.0":
        raise SystemExit("expected lucide-react 0.577.0 (the website's version), found " + version)
    icons_dir = os.path.join(root, "dist", "esm", "icons")
    out = [
        "// GENERATED by test/exam/runner/gen/gen_lucide_glyphs.py from lucide-react %s (ISC licence)." % version,
        "// Do not edit by hand. The website's runner icons, as vector nodes on lucide's 24-unit grid.",
        "import 'lucide_icon.dart';",
        "",
        "/// The lucide icons the runner uses (each cites where the website uses it).",
        "abstract final class LucideGlyphs {",
    ]
    for file, dart, used in ICONS:
        nodes = read_nodes(icons_dir, file)
        out.append("  /// `%s` — %s" % (file, used))
        out.append("  static const %s = LucideGlyph('%s', [" % (dart, file))
        for tag, a in nodes:
            out.append("    %s," % dart_node(tag, a))
        out.append("  ]);")
        out.append("")
    out[-1] = "}"
    print("\n".join(out))


if __name__ == "__main__":
    main()
